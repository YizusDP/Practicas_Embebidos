#!/usr/bin/env python3
# Genera st7796s.bin para el driver panel-mipi-dbi
import sys

MADCTL = int(sys.argv[1], 16) if len(sys.argv) > 1 else 0x28   # 0x28 horizontal, 0xE8 girada 180

SEQ = [
    (0x11, []), "120",
    (0x36, [MADCTL]),
    (0x3A, [0x55]),
    (0xF0, [0xC3]),
    (0xF0, [0x96]),
    (0xB4, [0x02]),
    (0xB7, [0xC6]),
    (0xC0, [0xC0, 0x00]),
    (0xC1, [0x13]),
    (0xC2, [0xA7]),
    (0xC5, [0x21]),
    (0xE8, [0x40, 0x8A, 0x1B, 0x1B, 0x23, 0x0A, 0xAC, 0x33]),
    (0xE0, [0xD2, 0x05, 0x08, 0x06, 0x05, 0x02, 0x2A, 0x44, 0x46, 0x39, 0x15, 0x15, 0x2D, 0x32]),
    (0xE1, [0x96, 0x08, 0x0C, 0x09, 0x09, 0x25, 0x2E, 0x43, 0x42, 0x35, 0x11, 0x11, 0x28, 0x2E]),
    (0xF0, [0x3C]),
    (0xF0, [0x69]), "120",
    (0x20, []),
    (0x29, []),
]

blob = bytearray(b"MIPI DBI" + bytes(7) + bytes([1]))   # magic (15 bytes) + version 1
for item in SEQ:
    if isinstance(item, str):
        blob += bytes([0x00, 1, int(item)])             # delay en ms
    else:
        cmd, args = item
        blob += bytes([cmd, len(args), *args])

open("st7796s.bin", "wb").write(blob)
print(f"st7796s.bin: {len(blob)} bytes, MADCTL=0x{MADCTL:02X}")
